/// Own map labels so that countries and cities follow the game language
/// (the base map tiles are drawn WITHOUT any text).
class GeoLabel {
  final double lat, lng, minZoom;
  final bool city;
  final String ru, en, uk;

  /// Country label: visible from [minZoom] up to about zoom 6.
  const GeoLabel.country(this.lat, this.lng, this.ru, this.en, this.uk, [this.minZoom = 3.5]) : city = false;

  /// City label: visible from [minZoom] and closer.
  const GeoLabel.city(this.lat, this.lng, this.ru, this.en, this.uk, [this.minZoom = 5]) : city = true;

  String name(String lang) => lang == 'ru' ? ru : (lang == 'uk' ? uk : en);
}

