/// Map labels in the game language (the map tiles themselves have no text).
class GeoLabel {
  final List<String> names; // ru, en, uk
  final double lat, lng;
  final int rank; // 1 = major city, 2 = smaller city (ignored for countries)
  const GeoLabel(this.names, this.lat, this.lng, [this.rank = 1]);

  String name(String lang) {
    final i = const ['ru', 'en', 'uk'].indexOf(lang);
    return names[i < 0 ? 0 : i];
  }
}

